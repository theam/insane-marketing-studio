#!/usr/bin/env python3
"""Generated clips into the page: extract each picked take's window to frames that genSlot()/drawGen() play.

Extracted from the Shepherdr production (epi.py, the frame and ramp parts). gen/picks.json:

  {"shots": {
     "hey":   {"take": "gen/clips/e5/take-3.mp4", "from": 0.0, "to": 3.6},
     "leave": {"take": "gen/clips/e7/take-2.mp4", "from": 0.2, "to": 3.0,
               "ramps": [[0.45, 1.85, 2.8]],          take seconds 0.45-1.85 play at 2.8×
               "delogo": [100, 330, 24, 16]}}}         a logo the model drew, in take px: x y w h

  studio clip-frames      → assets/gen/<shot>/000.jpg… at the project's fps, and assets/gen/manifest.js (window.GEN)

A speed ramp drops frames, but each output frame averages the source frames it spans, 1-2-1 weighted, so the steps
read as motion and not as a stutter: use it to cut a dead hold (the director: the eye roll shouldn't hold). Never slow a take
down. Morphs between takes read as strange camera moves: cut instead.
"""
import json, os, shutil, subprocess, tempfile
from pathlib import Path

ROOT = Path(os.environ.get("PROJECT_DIR", ".")).resolve()
GEN = ROOT / "assets/gen"
W = 1280


def run(*a):
    return subprocess.run(a, check=True, capture_output=True, text=True).stdout


def ramp_map(ramps, a, b):
    """Speed ramps [[t0, t1, speed], …] in take seconds → (take time of shot time u, shot time of take time, shot length)."""
    segs, u = [], 0.0
    cuts = sorted((max(a, t0), min(b, t1), sp) for t0, t1, sp in ramps if t1 > a and t0 < b)
    tau = a
    for t0, t1, sp in cuts + [(b, b, 1.0)]:
        if t0 > tau:
            segs.append((tau, t0, 1.0, u)); u += t0 - tau
        if t1 > t0:
            segs.append((t0, t1, sp, u)); u += (t1 - t0) / sp
        tau = max(tau, t1)

    def take_at(x):
        for f, t, sp, u0 in segs:
            if x < u0 + (t - f) / sp or (f, t, sp, u0) == segs[-1]:
                return f + (x - u0) * sp, sp

    def shot_at(t_):
        for f, t, sp, u0 in segs:
            if t_ <= t:
                return u0 + (max(t_, f) - f) / sp
        return u
    return take_at, shot_at, u


def extract(src, a, b, out, vf, fps):
    n = round((b - a) * fps)
    run("ffmpeg", "-y", "-loglevel", "error", "-i", str(src), "-ss", f"{a}", "-t", f"{b - a}", "-vf", vf + f"fps={fps},scale={W}:-2",
        "-frames:v", str(n), "-q:v", "3", "-start_number", "0", str(out / "%03d.jpg"))


def extract_ramped(src, a, b, ramps, out, vf, fps, tmp):
    take_at, _, dur = ramp_map(ramps, a, b)
    raw = tmp / "src"; raw.mkdir()
    rate = eval(run("ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=r_frame_rate", "-of", "csv=p=0", str(src)).strip())
    run("ffmpeg", "-y", "-loglevel", "error", "-i", str(src), "-vf", vf + f"scale={W}:-2", "-fps_mode", "passthrough", "-q:v", "2", "-start_number", "0", str(raw / "%04d.jpg"))
    srcs = sorted(raw.glob("*.jpg"))
    for k in range(round(dur * fps)):
        t, sp = take_at(k / fps)
        i = min(len(srcs) - 1, round(t * rate))
        o = out / f"{k:03d}.jpg"
        if sp <= 1.0:
            shutil.copy(srcs[i], o); continue
        span = max(1, round(sp * rate / fps / 2))
        js = [min(len(srcs) - 1, max(0, i + d)) for d in range(-span, span + 1)]
        wts = [span + 1 - abs(d) for d in range(-span, span + 1)]
        run("ffmpeg", "-y", "-loglevel", "error", *[x for j in js for x in ("-i", str(srcs[j]))],
            "-filter_complex", f"mix=inputs={len(js)}:weights='{' '.join(map(str, wts))}'", "-q:v", "3", str(o))
    return dur


def main():
    fps = json.loads((ROOT / "project.json").read_text()).get("fps", 30)
    picks = json.loads((ROOT / "gen/picks.json").read_text())["shots"]
    manifest = {}
    for shot, p in picks.items():
        src, a, b = ROOT / p["take"], p.get("from", 0.0), p["to"]
        out = GEN / shot
        shutil.rmtree(out, ignore_errors=True); out.mkdir(parents=True)
        vf = "delogo=x={}:y={}:w={}:h={},".format(*p["delogo"]) if p.get("delogo") else ""
        if p.get("ramps"):
            with tempfile.TemporaryDirectory() as tmp:
                dur = extract_ramped(src, a, b, p["ramps"], out, vf, fps, Path(tmp))
        else:
            extract(src, a, b, out, vf, fps); dur = b - a
        n = len(list(out.glob("*.jpg")))
        manifest[shot] = {"frames": n, "fps": fps, "dur": round(dur, 3)}
        print(f"{shot}: {p['take']} {a}-{b} s → {n} frames ({dur:.2f} s{', ramped' if p.get('ramps') else ''})")
    (GEN / "manifest.js").write_text("// Generated by `studio clip-frames` from gen/picks.json.\nwindow.GEN = " + json.dumps(manifest, indent=1) + ";\n")


if __name__ == "__main__":
    main()
