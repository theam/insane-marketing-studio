#!/usr/bin/env python3
"""Track a screen through a generated clip, to corner-pin a UI onto it (pinTo() in the page).

Extracted from the Shepherdr production (epi.py, the screen part). You measure the screen's four
corners once, on a reference frame of the extracted shot; each frame is then registered to that reference with macOS
Vision (VNHomographicImageRegistrationRequest on a crop around the screen), the reference quad is carried into the
frame through the homography, and the track is smoothed over 5 frames.

  studio cornerpin SHOT --quad "x,y x,y x,y x,y" --crop "x y w h" [--ref 0]
      SHOT   a shot already extracted by `studio clip-frames` (assets/gen/SHOT/)
      quad   the screen's corners on the reference frame, TL TR BR BL, in the extracted frame's px (1280 wide)
             (a corner may sit off-frame when the screen runs past the edge)
      crop   a box around the screen (and a little of what holds it still), in the same px
  → assets/gen/SHOT-screen.js: window.SCREENS[SHOT] = {src: [w, h], quads: [[TL, TR, BR, BL], …]} per frame

Check it on stills before the render (the director: every corner must land exactly). If the plate keeps the screen at the wrong
angle, change the camera instead of re-generating the same plate.
"""
import argparse, json, os, subprocess, tempfile
from pathlib import Path

ROOT = Path(os.environ.get("PROJECT_DIR", ".")).resolve()


def apply(M, p):
    x, y = p
    X, Y, Z = (M[r][0] * x + M[r][1] * y + M[r][2] for r in range(3))
    return (X / Z, Y / Z)


def inv(M):
    a, b, c = M[0]; d, e, f = M[1]; g, h, i = M[2]
    A, B, C = e * i - f * h, -(d * i - f * g), d * h - e * g
    det = a * A + b * B + c * C
    return [[A / det, -(b * i - c * h) / det, (b * f - c * e) / det],
            [B / det, (a * i - c * g) / det, -(a * f - c * d) / det],
            [C / det, -(a * h - b * g) / det, (a * e - b * d) / det]]


def smooth(track, k=2):
    out = []
    for i in range(len(track)):
        win = track[max(0, i - k): i + k + 1]
        out.append([(sum(q[j][0] for q in win) / len(win), sum(q[j][1] for q in win) / len(win)) for j in range(4)])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("shot"); ap.add_argument("--quad", required=True); ap.add_argument("--crop", required=True)
    ap.add_argument("--ref", type=int, default=0)
    a = ap.parse_args()
    frames = sorted((ROOT / "assets/gen" / a.shot).glob("*.jpg"))
    if not frames:
        raise SystemExit(f"no frames in assets/gen/{a.shot}: run `studio clip-frames` first")
    quad = [tuple(map(float, p.split(","))) for p in a.quad.split()]
    crop = a.crop.split()
    w, h = map(int, subprocess.check_output(["sips", "-g", "pixelWidth", "-g", "pixelHeight", str(frames[0])], text=True).split()[-3::2])
    ref = frames[a.ref]
    track = []
    with tempfile.TemporaryDirectory() as tmp:
        for f in frames:
            png = Path(tmp) / "f.png"
            subprocess.run(["sips", "-s", "format", "png", str(f), "--out", str(png)], check=True, capture_output=True)
            out = subprocess.run(["track", "reg", str(ref), str(png), *crop], capture_output=True, text=True).stdout.split()
            if len(out) != 9:
                track.append(track[-1] if track else quad); continue
            v = list(map(float, out))
            H = [v[0:3], v[3:6], v[6:9]]                # frame → reference
            track.append([apply(inv(H), p) for p in quad])
    data = {"src": [w, h], "quads": [[[round(x, 2), round(y, 2)] for x, y in q] for q in smooth(track)]}
    js = ROOT / f"assets/gen/{a.shot}-screen.js"
    js.write_text(f"// Generated by `studio cornerpin {a.shot}`.\nwindow.SCREENS = window.SCREENS || {{}};\nwindow.SCREENS[{json.dumps(a.shot)}] = {json.dumps(data)};\n")
    print(f"{js.relative_to(ROOT)}: {len(track)} frames tracked. In the page: <script src=\"{js.relative_to(ROOT)}\"></script>, then pinTo(el, w, h, SCREENS['{a.shot}'], t, a).")


if __name__ == "__main__":
    main()
